import type { MaintenanceStatusDto, PrewarmResultDto } from './flow.types.js';

export function formatEmergencyCacheHub(status: MaintenanceStatusDto, noticeText?: string): string {
  let banner = '';
  if (noticeText) {
    banner = `✨ *${noticeText}*\n────────────────────────────\n\n`;
  }

  const modeText = status.isMaintenanceActive
    ? '🛑 *مفعل (البوت مغلق أمام جميع المستخدمين الميدانيين)*'
    : '🟢 *غير مفعل (البوت متاح ويعمل لجميع المستخدمين طبيعياً)*';

  return (
    `${banner}` +
    `🛑 *صمامات التحكم الإداري وحالات الطوارئ*\n` +
    `────────────────────────────\n` +
    `أدوات التحكم السيادي اللحظية في تشغيل المنظومة والذاكرة المؤقتة:\n\n` +
    `🔹 *حالة وضع الصيانة الطارئ:* ${modeText}\n\n` +
    `📌 *آلية قفل الصيانة:* عند تفعيل هذا الوضع، يتم فوراً حجب كافة الأوامر والرسائل عن جميع المستخدمين الميدانيين (المشرفين، العمال، المحاسبين، والموردين) وتظهر لهم رسالة اعتذار رسمية، مع إبقاء صلاحية الوصول مفتوحة للسوبر أدمن فقط لإجراء التحديثات الميدانية بأمان.\n\n` +
    `🔄 *إعادة تدفئة الذاكرة اللحظية:* يقوم بتطهير كاش Redis وإعادة تحميل بيانات كافة العمال والمشاريع والأقسام في ذاكرة الـ RAM للعمل بسرعة فائقة (< 15ms) دون الحاجة لإعادة تشغيل خادم البوت.\n` +
    `────────────────────────────\n` +
    `👇 *اختر الإجراء المطلوب:*`
  );
}

export function formatMaintenancePromptCard(): string {
  return (
    `🛑 *تأكيد تفعيل وضع الصيانة الطارئ (Emergency Maintenance)*\n` +
    `────────────────────────────\n` +
    `⚠️ *هل أنت متأكد من رغبتك في إغلاق البوت فوراً أمام كافة المستخدمين الميدانيين؟*\n\n` +
    `سيتم إيقاف الاستجابة للجميع مع رسالة اعتذار حتى تقوم بإلغاء التفعيل يدوياً، وسيظل البوت متاحاً لك فقط كمدير عام.`
  );
}

export function formatPrewarmSummary(res: PrewarmResultDto): string {
  return (
    `🔄 *تقرير إعادة تدفئة الذاكرة اللحظية (Cache Pre-Warm)*\n` +
    `────────────────────────────\n` +
    `✅ *تم تفريغ وإعادة شحن الذاكرة اللحظية بنجاح:*\n` +
    `• العمالة النشطة المحملة في RAM: *${res.workersLoaded} عامل*\n` +
    `• المواقع والفروع الميدانية: *${res.sitesLoaded} موقع*\n` +
    `• الأقسام والوظائف المعتمدة: *${res.departmentsLoaded} قسم / ${res.jobsLoaded} مهنة*\n` +
    `• زمن إعادة التدفئة الكلي: *${res.durationMs}ms*\n` +
    `• الذاكرة الحالية المستهلكة: *${res.memoryUsedMb} MB*\n\n` +
    `⚡ المنظومة جاهزة الآن للاستجابة اللحظية الميدانية دون أي تأخير.`
  );
}
